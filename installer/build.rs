//! Builds the Monolith player, then embeds the resulting executable and icon
//! into the installer so `monolith-setup.exe` is a single self-contained file
//! the user can copy anywhere and run.

use std::{env, fs, path::PathBuf, process::Command};

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest
        .parent()
        .expect("installer sits beside the player")
        .to_path_buf();

    println!("cargo:rerun-if-changed=../Cargo.toml");
    println!("cargo:rerun-if-changed=../build.rs");
    println!("cargo:rerun-if-changed=../ui");
    println!("cargo:rerun-if-changed=../src");
    println!("cargo:rerun-if-changed=../assets");

    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        // The installer is Windows-only; skip the embedded payload elsewhere.
        return;
    }

    // The interface lives beside the player and imports ../controls.slint, so
    // it is compiled in place rather than copied into OUT_DIR.
    let interface = root.join("ui/installer/setup.slint");
    assert!(interface.is_file(), "missing {}", interface.display());
    slint_build::compile(&interface).expect("Could not compile the installer interface");

    println!("cargo:rerun-if-env-changed=MONOLITH_PLAYER_EXE");
    let built = if let Some(payload) = env::var_os("MONOLITH_PLAYER_EXE") {
        let path = PathBuf::from(payload)
            .canonicalize()
            .expect("resolve supplied player");
        println!("cargo:rerun-if-changed={}", path.display());
        let header = fs::read(&path).expect("read supplied player");
        assert!(
            header.starts_with(b"MZ"),
            "payload must be a Windows executable"
        );
        path
    } else {
        // Reuse the player cache; a nested copy cost roughly 2 GiB.
        let app_target = root.join("target");
        let status = Command::new(env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
            .current_dir(&root)
            .args([
                "build",
                "--release",
                "--locked",
                "--offline",
                "--bin",
                "monolith-desktop",
                "-j",
                "4",
            ])
            .env("CARGO_TARGET_DIR", &app_target)
            .status()
            .expect("could not build the player");
        assert!(
            status.success(),
            "the player must build before the installer"
        );
        app_target.join("release/monolith-desktop.exe")
    };
    stage_sealed_name(&root, &out_dir);

    let icon = root.join("assets/monolith.ico");
    for input in [&built, &icon] {
        assert!(input.is_file(), "missing build input: {}", input.display());
    }

    let staged = out_dir.join("payload");
    fs::create_dir_all(&staged).expect("create payload directory");
    fs::copy(&built, staged.join("monolith-desktop.exe")).expect("stage player");
    fs::copy(&icon, staged.join("monolith.ico")).expect("stage icon");
}

/// Lifts the sealed NAME array out of the player's generated `identity_data.rs`
/// so the installer can decode it without linking the player crate.
fn stage_sealed_name(root: &PathBuf, out_dir: &PathBuf) {
    let generated = root.join("src/identity_data.rs");
    let text = fs::read_to_string(&generated)
        .unwrap_or_else(|error| panic!("read {}: {error}", generated.display()));
    let start = text
        .find("pub const NAME: [u8;")
        .expect("identity_data.rs must declare NAME");
    // The first bracket pair is the type `[u8; 11]`, not the literal. Step over
    // it before looking for the values.
    let type_end = text[start..].find(']').expect("array type") + start;
    let open = text[type_end..].find('[').expect("array literal") + type_end;
    let close = text[open..].find(']').expect("array literal") + open;
    let body: Vec<&str> = text[open + 1..close]
        .split(',')
        .map(str::trim)
        .filter(|token| !token.is_empty())
        .collect();
    assert!(!body.is_empty(), "sealed NAME array is empty");
    let length = body.len();
    let formatted: Vec<String> = body
        .chunks(12)
        .map(|chunk| format!("    {},\n", chunk.join(", ")))
        .collect();
    // Plain comments, not `//!`: this file is `include!`d rather than a module
    // root, so an inner doc comment has nowhere legal to go.
    let generated_rs = format!(
        "// Generated by installer/build.rs from the player's sealed payload.\n\
         // The name is never a plain string in this binary.\n\
         pub const SEALED_NAME: [u8; {length}] = [\n{}\n];\n",
        formatted.join("")
    );
    fs::write(out_dir.join("sealed_name.rs"), generated_rs).expect("stage sealed name");
}
