//! Turns an unexpected panic into something a person can act on.
//!
//! A native player that dies silently is a bug report nobody can file. When the
//! event loop unwinds, this builds a short report, keeps a copy on disk, and
//! shows a dialog whose real action opens the project's issue tracker with the
//! details already typed out.

use std::{fmt::Write as _, panic::PanicHookInfo, path::PathBuf};

use crate::{identity::Identity, version::VERSION};

/// Where "Report" sends people.
///
/// Sealed alongside the rest of the identity, because the repository slug
/// carries the same handle as the developer card: written here as a literal it
/// went back into plain text in both shipped binaries. This is the one place to
/// change if the desktop app is ever published under its own repository.
fn issue_repo() -> String {
    Identity::default().issue_repo
}

/// Percent-encodes for a query string. GitHub only needs a conservative set;
/// leaving anything else alone would truncate the body at the first space.
fn encode(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for byte in text.bytes() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(byte as char);
            }
            _ => out.push_str(&format!("%{byte:02X}")),
        }
    }
    out
}

/// The one-line summary shown in the dialog and used as the issue title.
pub fn headline(payload: &str) -> String {
    let first = payload.lines().next().unwrap_or("").trim();
    if first.is_empty() {
        "unknown panic".to_string()
    } else {
        // A panic message can be arbitrarily long; the title cannot.
        first.chars().take(120).collect()
    }
}

/// The full report: what happened, on which build, and where the log went.
pub fn report(payload: &str) -> String {
    let mut text = format!("Monolith {VERSION} stopped unexpectedly.\n\n");
    let _ = writeln!(text, "```\n{}\n```", payload.trim());
    if let Some(path) = log_path() {
        let _ = writeln!(text, "\nA copy was written to {}.", path.display());
    }
    text
}

/// Appends the report to a log beside the library, newest last, so repeat
/// crashes accumulate instead of overwriting each other.
pub fn save(text: &str) -> Option<PathBuf> {
    let path = log_path()?;
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).ok()?;
    }
    use std::io::Write as _;
    let mut file = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&path)
        .ok()?;
    writeln!(file, "\n--- {stamp} ---\n{text}", stamp = timestamp()).ok()?;
    Some(path)
}

fn log_path() -> Option<PathBuf> {
    Some(
        PathBuf::from(std::env::var_os("LOCALAPPDATA")?)
            .join("Programs")
            .join("Monolith")
            .join("crash.log"),
    )
}

/// A stamp for the log. Wall-clock formatting would mean a dependency, and all
/// a human needs here is an ordering and a rough age.
fn timestamp() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let (mins, hours) = (secs / 60 % 60, secs / 3600 % 24);
    format!("session uptime {hours}h {mins}m, unix {secs}")
}

/// The prefilled "new issue" address. Everything the user does not have to type
/// is already in the link, including the whole report.
pub fn issue_url(summary: &str, details: &str) -> String {
    let title = format!("Crash: {}", headline(summary));
    let body = format!(
        "<!-- generated by Monolith {VERSION} -->\n\n\
         Monolith stopped unexpectedly and I would like this looked at.\n\n\
         **Details**\n\n```\n{}\n```\n",
        details.trim()
    );
    format!(
        "https://github.com/{repo}/issues/new?title={title}&body={body}",
        repo = issue_repo(),
        title = encode(&title),
        body = encode(&body)
    )
}

/// Installs a hook that records the panic before it unwinds. The default hook
/// still runs, so the text is not lost when no dialog can be shown.
pub fn install_hook() {
    let previous = std::panic::take_hook();
    std::panic::set_hook(Box::new(move |info: &PanicHookInfo| {
        previous(info);
        let payload = info
            .payload()
            .downcast_ref::<&str>()
            .map(|s| (*s).to_string())
            .or_else(|| info.payload().downcast_ref::<String>().cloned())
            .unwrap_or_else(|| "unknown panic".to_string());
        // Best effort: a failure to write must not replace the real panic with
        // a different one.
        let _ = save(&report(&payload));
    }));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn encoding_escapes_what_a_query_string_cannot_carry() {
        assert_eq!(encode("a b"), "a%20b");
        assert_eq!(encode("a+b&c=d"), "a%2Bb%26c%3Dd");
        assert_eq!(encode("safe-._~"), "safe-._~");
    }

    #[test]
    fn the_issue_link_carries_the_title_and_the_report() {
        let url = issue_url("index out of bounds", "panicked at src/main.rs");
        assert!(url.starts_with(&format!("https://github.com/{}/issues/new?", issue_repo())));
        assert!(url.contains("title=Crash%3A"));
        assert!(url.contains("src%2Fmain.rs"));
    }

    #[test]
    fn a_blank_panic_still_produces_a_usable_headline() {
        assert_eq!(headline("\n  \n"), "unknown panic");
        assert_eq!(headline(""), "unknown panic");
        assert_eq!(headline("index out of bounds"), "index out of bounds");
        // A long panic is trimmed rather than shoved through a URL whole.
        assert_eq!(headline(&"x".repeat(500)).chars().count(), 120);
    }

    #[test]
    fn the_report_names_the_build_and_quotes_the_panic() {
        let text = report("boom");
        assert!(text.contains(VERSION), "the report must name the build");
        assert!(text.contains("boom"));
    }

    #[test]
    fn a_panic_message_cannot_redirect_the_report_somewhere_else() {
        // A panic message can carry anything a filename or a path can, so the
        // origin has to be fixed and the message confined to the query.
        let url = issue_url("p", "file:///C:/Windows/System32/cmd.exe");
        let origin = format!("https://github.com/{}/issues/new?", issue_repo());
        assert!(url.starts_with(&origin), "the origin must be fixed: {url}");
        // Nothing from the message survives unencoded, so it cannot add a
        // parameter, a fragment, or a second address of its own.
        let query = &url[origin.len()..];
        assert!(!query.contains('\n') && !query.contains('\r'));
        assert!(!query.contains("://"));
        assert_eq!(query.matches('&').count(), 1, "only the title and body");
    }

    #[test]
    fn the_sealed_issue_tracker_decodes_to_an_owner_and_a_repository() {
        let repo = issue_repo();
        let (owner, name) = repo.split_once('/').expect("owner/repository");
        assert!(!owner.is_empty() && !name.is_empty());
        assert!(!owner.contains(char::is_whitespace));
    }
}
